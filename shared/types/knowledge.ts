import { type AttributeDefinition, type AttributeImpact, type AttributeValue } from "./attributes";
import { type Backlink, type CommitResult, type BlockDeletion, type ChangePreview, type EditCommit, type KnowledgeChange, type Placement, type ResolvedTarget, type PageKind, type PageList, type PageQuery, type PageRecord, type PageObjects, type Target } from "./content";
import { type AnchorInput, type PaperImport, type PaperResources, type ReadingPosition } from "./papers";

export type HistoryState = { canUndo: boolean; redo: { id: string; time: number }[] };
export type Notice = { id: string; pageId: string; title: string; createdAt: number; isRead: boolean };
export type KnowledgeAPI = {
    list(query?: PageQuery): Promise<PageList>;
    get(id: string): Promise<PageRecord>;
    readObjects(pageId: string, ids: string[]): Promise<PageObjects>;
    create(kind: PageKind, title?: string, initial?: Record<string, AttributeValue>, parentId?: string, tabId?: string): Promise<PageRecord>;
    commitEdit(input: EditCommit, confirmation?: string): Promise<CommitResult>;
    previewEdit(input: EditCommit): Promise<ChangePreview | null>;
    deleteBlock(input: BlockDeletion, confirmation?: string): Promise<CommitResult>;
    place(input: Placement, confirmation?: string): Promise<CommitResult>;
    trash(ids: string[], tabId: string, confirmation?: string): Promise<CommitResult>;
    restore(ids: string[], tabId: string): Promise<CommitResult>;
    definitions(): Promise<AttributeDefinition[]>;
    define(id: string, value: AttributeDefinition | null, token?: string): Promise<AttributeImpact | null>;
    backlinks(id: string): Promise<Backlink[]>;
    resolve(target: Target): Promise<ResolvedTarget | null>;
    history(tabId: string): Promise<HistoryState>;
    undo(tabId: string, direction: "undo" | "redo", branchId?: string, confirmation?: string): Promise<CommitResult>;
    closeTab(tabId: string): Promise<void>;
    loadTabs(): Promise<unknown>;
    saveTabs(value: unknown): Promise<void>;
    importPDF(pageId?: string, tabId?: string): Promise<PaperImport | null>;
    resources(pageId: string): Promise<PaperResources>;
    readFile(fileId: string): Promise<Uint8Array>;
    position(pageId: string, fileId: string, value: ReadingPosition, tabId?: string): Promise<void>;
    highlight(pageId: string, anchor: AnchorInput, color: string, tabId?: string): Promise<void>;
    removeHighlight(id: string, tabId?: string): Promise<void>;
    annotate(pageId: string, anchor: AnchorInput, tabId?: string): Promise<string>;
    notices(): Promise<Notice[]>;
    readNotice(id: string): Promise<void>;
    onChanged(listener: (change: KnowledgeChange) => void): () => void;
    onCloseRequested(listener: () => Promise<boolean>): () => void;
};