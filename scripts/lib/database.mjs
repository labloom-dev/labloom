import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { isDeepStrictEqual } from "node:util";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { generateSQLiteDrizzleJson, generateSQLiteMigration } from "drizzle-kit/api";

const separator = "\n--> statement-breakpoint\n";

export function baselineDirectory(root) {
    return join(root, "main/storage/migrations/generated");
}

export function splitSql(sql) {
    return sql.trim().split(/^--> statement-breakpoint\s*$/m).map(part => part.trim()).filter(Boolean);
}

function validateRules(rules) {
    const names = new Set();
    for (const statement of splitSql(rules)) {
        const match = /^CREATE (TRIGGER|VIEW) ([a-z_][a-z0-9_]*)\b/i.exec(statement);
        if (!match || names.has(match[2])) throw new Error("rules.sql must contain uniquely named CREATE TRIGGER/VIEW statements separated by statement-breakpoint markers.");
        names.add(match[2]);
    }
}

async function baseline(root) {
    const tables = await import(pathToFileURL(join(root, "main/storage/tables.ts")).href);
    const snapshot = await generateSQLiteDrizzleJson(tables);
    const rules = (await readFile(join(root, "main/storage/rules.sql"), "utf8")).trim();
    validateRules(rules);
    const options = JSON.parse(await readFile(join(root, "main/storage/table-options.json"), "utf8"));
    if (Object.keys(options).join() !== "strictTables" || !Array.isArray(options.strictTables)
        || new Set(options.strictTables).size !== options.strictTables.length
        || options.strictTables.some(name => !Object.hasOwn(snapshot.tables, name))) {
        throw new Error("table-options.json must list existing tables once under strictTables.");
    }
    const empty = await generateSQLiteDrizzleJson({});
    const statements = (await generateSQLiteMigration(empty, snapshot)).map(statement => {
        const name = /^CREATE TABLE [`"]([^`"]+)[`"]/.exec(statement)?.[1];
        return options.strictTables.includes(name) ? statement.replace(/\);\s*$/, ") STRICT;") : statement;
    });
    return [...statements, ...splitSql(rules)].map(statement => statement.trim()).filter(Boolean).join(separator);
}

function runtimeModule(sql) {
    return `// Generated by pnpm db:generate. Do not edit by hand.
// Embed the single baseline so packaged applications need no SQL file paths.
export const baselineVersion = 1;
export const baselineSql = ${JSON.stringify(sql)};`;
}

export async function checkBaseline(root) {
    const directory = baselineDirectory(root);
    if (!isDeepStrictEqual((await readdir(directory)).sort(), ["baseline.sql", "index.ts"])) {
        throw new Error("Expected only baseline.sql and index.ts in the generated baseline directory.");
    }
    const expected = await baseline(root);
    if (await readFile(join(directory, "baseline.sql"), "utf8") !== expected) {
        throw new Error("Database definitions and baseline SQL differ. Run pnpm db:generate.");
    }
    if (await readFile(join(directory, "index.ts"), "utf8") !== runtimeModule(expected)) {
        throw new Error("Embedded baseline differs from SQL. Run pnpm db:generate.");
    }
}

export async function generateBaseline(root) {
    const sql = await baseline(root);
    const directory = baselineDirectory(root);
    await mkdir(directory, { recursive: true });
    let changed = false;
    for (const [name, content] of [["baseline.sql", sql], ["index.ts", runtimeModule(sql)]]) {
        const path = join(directory, name);
        const previous = await readFile(path, "utf8").catch(error => {
            if (error.code !== "ENOENT") throw error;
            return null;
        });
        if (previous === content) continue;
        await writeFile(path, content);
        changed = true;
    }
    return changed ? "Regenerated the single baseline. Run pnpm db:check and pnpm test:db."
        : "No database definition changes; no files written.";
}